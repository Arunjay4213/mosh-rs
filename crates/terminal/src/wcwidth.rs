/// glibc wcwidth() for code point `c` (C.UTF-8). Returns -1 for values above 0x10FFFF.
pub fn wcwidth(c: u32) -> i32 {
    match WCWIDTH_TABLE.binary_search_by(|&(lo, hi, _)| {
        if hi < c {
            core::cmp::Ordering::Less
        } else if lo > c {
            core::cmp::Ordering::Greater
        } else {
            core::cmp::Ordering::Equal
        }
    }) {
        Ok(i) => WCWIDTH_TABLE[i].2 as i32,
        Err(_) => -1,
    }
}
