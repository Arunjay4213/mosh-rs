/// Generic entries setupterm refuses (errret 0 for a listed name), sorted.
pub static GENERIC: &[&str] = &["ibm327x", "unknown"];

/// What `mosh-client -c` prints for `term` (the TERM value): the color
/// count (`tigetnum("colors")`, -1 when absent), or the message ncurses'
/// `setupterm` prints before upstream exits with status 1. An unknown
/// name gets xterm's count, where upstream reports it (PLAN.md 9.6).
pub fn colors(term: Option<&str>) -> Result<i32, String> {
    let t = match term {
        None | Some("") => return Err("TERM environment variable not set.".to_string()),
        Some(t) => t,
    };
    if HARDCOPY.binary_search(&t).is_ok() {
        return Err(format!("'{t}': I can't handle hardcopy terminals."));
    }
    if GENERIC.binary_search(&t).is_ok() {
        return Err(format!("'{t}': I need something more specific."));
    }
    let caps = lookup(t)
        .or_else(|| lookup("xterm"))
        .expect("the generated terminfo table has an xterm entry");
    Ok(caps.colors)
}
