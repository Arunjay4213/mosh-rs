/// The capabilities for terminal type `name`, if the database has it.
pub fn lookup(name: &str) -> Option<&'static TermCaps> {
    NAMES
        .binary_search_by(|(n, _)| (*n).cmp(name))
        .ok()
        .map(|i| &CAPS[NAMES[i].1 as usize])
}

